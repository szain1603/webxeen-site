#!/usr/bin/env node
/*
  Pre-render the English home page into index.html so search engines see every word
  without running JavaScript. content.js and config.js stay the source of truth:
  in the browser, main.js rebuilds the same sections from them (and the language toggle
  keeps working). Re-run this after any change to content.js or config.js:

    npm i --no-save jsdom@24   (once, anywhere on NODE_PATH)
    node seo-agent/tools/prerender.js

  Only the part of index.html between the skip link and <noscript>, and the JSON-LD block
  in <head>, are rewritten.
*/
'use strict';
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const ROOT = path.resolve(__dirname, '..', '..');
const file = path.join(ROOT, 'index.html');
const src = fs.readFileSync(file, 'utf8');

const START = '<a class="skip" href="#main">Skip to content</a>';
const END = '<noscript>';
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < 0 || b < a) throw new Error('index.html markers not found');

const dom = new JSDOM(src, { url: 'https://webxeen.com/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.matchMedia = () => ({ matches: false, addListener() {}, addEventListener() {} });
w.WEBXEEN_PRERENDER = true;
for (const s of ['config.js', 'content.js', 'assets/js/main.js']) {
  w.eval(fs.readFileSync(path.join(ROOT, s), 'utf8'));
}
const d = w.document;
const header = d.querySelector('header.nav').outerHTML;
const main = d.querySelector('main#main').outerHTML;
const footer = d.querySelector('footer.foot').outerHTML;

// JSON-LD structured data, built from config.js + content.js so it always matches the page.
const CFG = w.WEBXEEN_CONFIG, EN = w.WEBXEEN_CONTENT.en;
const SITE = 'https://webxeen.com/';
const offers = [];
for (const p of CFG.pricing.plans) {
  const name = 'Webxeen ' + EN.pricing.names[p.id];
  for (const [cur, price] of [['USD', p.monthlyUSD], ['PKR', p.monthlyPKR]]) {
    offers.push({ '@type': 'Offer', name, price: String(price), priceCurrency: cur, url: SITE + '#pricing',
      priceSpecification: { '@type': 'UnitPriceSpecification', price: String(price), priceCurrency: cur, unitCode: 'MON', unitText: 'month' } });
  }
}
const ld = { '@context': 'https://schema.org', '@graph': [
  { '@type': 'Organization', '@id': SITE + '#org', name: 'Webxeen', url: SITE, logo: SITE + 'icon-512.png',
    email: CFG.links.contactEmail, description: EN.footer.tagline },
  { '@type': 'WebSite', '@id': SITE + '#website', name: 'Webxeen', url: SITE, inLanguage: 'en', publisher: { '@id': SITE + '#org' } },
  { '@type': 'SoftwareApplication', '@id': SITE + '#app', name: 'Webxeen', url: SITE,
    applicationCategory: 'BusinessApplication', operatingSystem: 'WhatsApp',
    description: EN.meta.description, image: SITE + 'og-image.jpg',
    publisher: { '@id': SITE + '#org' }, offers }
] };
const LD_START = '<!-- ld-json:start (generated by seo-agent/tools/prerender.js) -->', LD_END = '<!-- ld-json:end -->';
const ldBlock = LD_START + '\n<script type="application/ld+json">\n' + JSON.stringify(ld, null, 2).replace(/</g, '\\u003c') + '\n</script>\n' + LD_END;

const region = START + '\n\n' + header + '\n\n' + main + '\n\n<!-- 14. FOOTER ==================================================== -->\n' + footer + '\n\n';
let out = src.slice(0, a) + region + src.slice(b);
const l1 = out.indexOf(LD_START), l2 = out.indexOf(LD_END);
if (l1 >= 0 && l2 > l1) out = out.slice(0, l1) + ldBlock + out.slice(l2 + LD_END.length);
else out = out.replace('</head>', ldBlock + '\n</head>');
fs.writeFileSync(file, out);

// quick report
const words = (d.querySelector('main').textContent.match(/\S+/g) || []).length;
console.log('prerendered index.html: ' + words + ' words in <main>, ' + d.querySelectorAll('h1').length + ' h1, ' + d.querySelectorAll('h2').length + ' h2');
