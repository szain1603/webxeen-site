#!/usr/bin/env node
/*
  Pre-render the home page in every language so search engines see every word
  without running JavaScript. content.js and config.js stay the source of truth:
  in the browser, main.js rebuilds the same sections from them.

    npm i --no-save jsdom@24   (once, anywhere on NODE_PATH)
    node seo-agent/tools/prerender.js

  Writes:
    index.html     English (/). Only the part between the skip link and <noscript>,
                   the JSON-LD block and the hreflang block are rewritten; edit the rest by hand.
    ur/index.html  Roman Urdu (/ur). Fully generated from index.html + content.js "ur".
    ar/index.html  Arabic (/ar, right-to-left). Fully generated from index.html + content.js "ar".
    es/index.html  Spanish (/es). Fully generated from index.html + content.js "es".
                   Never edit these by hand: change index.html / content.js and re-run.
*/
'use strict';
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const ROOT = path.resolve(__dirname, '..', '..');
const SITE = 'https://webxeen.com/';

// One entry per language version. `extra` holds head text not found in content.js.
const PAGES = [
  { key: 'en', hreflang: 'en', url: SITE, file: 'index.html' },
  { key: 'ur', hreflang: 'ur-Latn', url: SITE + 'ur', file: 'ur/index.html',
    extra: {
      ogTitle: 'Webxeen — aap ki shop ka WhatsApp, 24/7 jawab bhi de, order bhi le',
      ogDescription: 'WhatsApp ke liye AI sales assistant: 8 zubaanon mein jawab, receipt ke saath orders, payment screenshot ki checking.',
      skip: 'Content par jayein',
      noscript: 'Videos chalane ke liye JavaScript on karein.'
    } },
  { key: 'ar', hreflang: 'ar', url: SITE + 'ar', file: 'ar/index.html',
    extra: {
      ogTitle: 'Webxeen — واتساب متجرك يرد على العملاء ويستقبل الطلبات 24/7',
      ogDescription: 'مساعد مبيعات ذكي لواتساب: يرد بـ 8 لغات منها العربية، يستقبل الطلبات بإيصالات، ويفحص صور إثبات الدفع.',
      skip: 'انتقل إلى المحتوى',
      noscript: 'فعّل JavaScript لتشغيل الفيديوهات.'
    } },
  { key: 'es', hreflang: 'es', url: SITE + 'es', file: 'es/index.html',
    extra: {
      ogTitle: 'Webxeen — el WhatsApp de tu negocio responde y toma pedidos 24/7',
      ogDescription: 'Asistente de ventas con IA para WhatsApp: responde en 8 idiomas, incluido el español, toma pedidos con recibo y revisa los comprobantes de pago.',
      skip: 'Ir al contenido',
      noscript: 'Activa JavaScript para ver los videos.'
    } }
];

const START = '<a class="skip" href="#main">Skip to content</a>';
const END = '<noscript>';
const LD_START = '<!-- ld-json:start (generated by seo-agent/tools/prerender.js) -->', LD_END = '<!-- ld-json:end -->';
const HL_START = '<!-- hreflang:start (generated by seo-agent/tools/prerender.js) -->', HL_END = '<!-- hreflang:end -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
function between(s, a, b, inner) {
  const i = s.indexOf(a), j = s.indexOf(b);
  if (i < 0 || j < i) throw new Error('markers not found: ' + a);
  return s.slice(0, i) + a + '\n' + inner + '\n' + s.slice(j);
}
function setMeta(s, re, value, what) {
  if (!re.test(s)) throw new Error('not found in index.html: ' + what);
  return s.replace(re, (m, pre, _old, post) => pre + esc(value) + post);
}

// Render index.html's body region with content.js in language `key`.
function renderBody(src, key) {
  const a = src.indexOf(START), b = src.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('index.html markers not found');
  const html = src.replace(/data-page-lang="[^"]*"/, 'data-page-lang="' + key + '"');
  const dom = new JSDOM(html, { url: SITE, runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  w.matchMedia = () => ({ matches: false, addListener() {}, addEventListener() {} });
  w.WEBXEEN_PRERENDER = true;
  for (const s of ['config.js', 'content.js', 'assets/js/main.js']) w.eval(fs.readFileSync(path.join(ROOT, s), 'utf8'));
  const d = w.document;
  const region = START + '\n\n' + d.querySelector('header.nav').outerHTML + '\n\n' + d.querySelector('main#main').outerHTML +
    '\n\n<!-- 14. FOOTER ==================================================== -->\n' + d.querySelector('footer.foot').outerHTML + '\n\n';
  const words = (d.querySelector('main').textContent.match(/\S+/g) || []).length;
  return { out: src.slice(0, a) + region + src.slice(b), words, h1: d.querySelectorAll('h1').length, h2: d.querySelectorAll('h2').length, w };
}

// JSON-LD structured data, built from config.js + content.js so it always matches the page.
function ldBlock(CFG, EN) {
  const offers = [];
  for (const p of CFG.pricing.plans) {
    const name = 'Webxeen ' + EN.pricing.names[p.id];
    for (const [cur, price] of [['USD', p.monthlyUSD], ['PKR', p.monthlyPKR]]) {
      offers.push({ '@type': 'Offer', name, price: String(price), priceCurrency: cur, url: SITE + '#pricing',
        priceSpecification: { '@type': 'UnitPriceSpecification', price: String(price), priceCurrency: cur, unitCode: 'MON', unitText: 'month' } });
    }
  }
  const ld = { '@context': 'https://schema.org', '@graph': [
    { '@type': 'Organization', '@id': SITE + '#org', name: 'Webxeen', url: SITE, logo: SITE + 'icon-512.png',
      email: CFG.links.contactEmail, description: EN.footer.tagline },
    { '@type': 'WebSite', '@id': SITE + '#website', name: 'Webxeen', url: SITE, inLanguage: PAGES.map((p) => p.hreflang), publisher: { '@id': SITE + '#org' } },
    { '@type': 'SoftwareApplication', '@id': SITE + '#app', name: 'Webxeen', url: SITE,
      applicationCategory: 'BusinessApplication', operatingSystem: 'WhatsApp',
      description: EN.meta.description, image: SITE + 'og-image.jpg',
      publisher: { '@id': SITE + '#org' }, offers }
  ] };
  return '<script type="application/ld+json">\n' + JSON.stringify(ld, null, 2).replace(/</g, '\\u003c') + '\n</script>';
}

const hreflang = PAGES.map((p) => '<link rel="alternate" hreflang="' + p.hreflang + '" href="' + p.url + '">').join('\n') +
  '\n<link rel="alternate" hreflang="x-default" href="' + SITE + '">';

// 1. English page (index.html, edited in place)
let src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const en = renderBody(src, 'en');
const CFG = en.w.WEBXEEN_CONFIG, TXT = en.w.WEBXEEN_CONTENT;
let enOut = between(en.out, LD_START, LD_END, ldBlock(CFG, TXT.en));
enOut = between(enOut, HL_START, HL_END, hreflang);
fs.writeFileSync(path.join(ROOT, 'index.html'), enOut);
console.log('index.html: ' + en.words + ' words in <main>, ' + en.h1 + ' h1, ' + en.h2 + ' h2');

// 2. Other languages, generated from the finished English page
for (const P of PAGES.filter((p) => p.key !== 'en')) {
  const M = TXT[P.key].meta, X = P.extra;
  const r = renderBody(enOut, P.key);
  let s = r.out;
  s = s.replace(/<html lang="[^"]*" dir="[^"]*" data-page-lang="[^"]*">/,
    '<html lang="' + M.lang + '" dir="' + (M.dir || 'ltr') + '" data-page-lang="' + P.key + '">');
  s = setMeta(s, /(<title>)([^<]*)(<\/title>)/, M.title, 'title');
  s = setMeta(s, /(<meta name="description" content=")([^"]*)(">)/, M.description, 'description');
  s = setMeta(s, /(<link rel="canonical" href=")([^"]*)(">)/, P.url, 'canonical');
  s = setMeta(s, /(<meta property="og:url" content=")([^"]*)(">)/, P.url, 'og:url');
  s = setMeta(s, /(<meta property="og:title" content=")([^"]*)(">)/, X.ogTitle, 'og:title');
  s = setMeta(s, /(<meta property="og:description" content=")([^"]*)(">)/, X.ogDescription, 'og:description');
  s = s.replace(START, '<a class="skip" href="#main">' + esc(X.skip) + '</a>');
  s = s.replace(/<noscript><p class="noscript">[^<]*<\/p><\/noscript>/, '<noscript><p class="noscript">' + esc(X.noscript) + '</p></noscript>');
  // The page lives in a sub-folder: make local file paths absolute (assets/x -> /assets/x).
  s = s.replace(/\b(href|src)="(?!https?:|\/|#|mailto:|data:|tel:)([^"]+)"/g, '$1="/$2"');
  s = s.replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by seo-agent/tools/prerender.js from index.html + content.js. Do not edit by hand. -->');
  fs.mkdirSync(path.dirname(path.join(ROOT, P.file)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, P.file), s);
  console.log(P.file + ': ' + r.words + ' words in <main>, ' + r.h1 + ' h1, ' + r.h2 + ' h2');
}
